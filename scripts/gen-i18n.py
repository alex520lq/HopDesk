#!/usr/bin/env python3
"""Generate and validate src/core/i18n_table.h from locales/*.lang (zero-dep key=value)."""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LOCALES = ROOT / 'locales'
OUT = ROOT / 'src/core/i18n_table.h'
LANGS = [('zh-CN', 'ZH_CN'), ('en', 'EN')]
FMT_RE = re.compile(r'%(?:%|[-+#0 ]*(?:\*|\d+)?(?:\.(?:\*|\d+))?(?:hh|h|ll|l|z)?[diuoxXfFeEgGaAcsp])')


def parse_lang(path: pathlib.Path) -> dict[str, str]:
    entries: dict[str, str] = {}
    for lineno, raw in enumerate(path.read_text(encoding='utf-8').splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith('#'):
            continue
        if '=' not in raw:
            raise SystemExit(f'{path}:{lineno}: missing "="')
        key, val = raw.split('=', 1)
        key = key.strip()
        if not re.fullmatch(r'[a-z0-9_]+(?:\.[a-z0-9_]+)*', key):
            raise SystemExit(f'{path}:{lineno}: invalid key "{key}"')
        if key in entries:
            raise SystemExit(f'{path}:{lineno}: duplicate key "{key}"')
        val = val.replace('\\n', '\n')
        entries[key] = val
    return entries


def fmt_signature(text: str) -> list[str]:
    return [m.group(0) for m in FMT_RE.finditer(text) if m.group(0) != '%%']


def c_escape(text: str) -> str:
    out = []
    for ch in text:
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif ch == '\n':
            out.append('\\n')
        elif ch == '\r':
            out.append('\\r')
        elif ch == '\t':
            out.append('\\t')
        else:
            out.append(ch)
    return '"' + ''.join(out) + '"'


def enum_name(key: str) -> str:
    return 'HOP_STR_' + key.upper().replace('.', '_')


def render_header(tables: dict[str, dict[str, str]], keys: list[str]) -> str:
    lines = [
        '/* Auto-generated by scripts/gen-i18n.py from locale files — DO NOT EDIT DIRECTLY. */',
        '#ifndef HOP_I18N_TABLE_H',
        '#define HOP_I18N_TABLE_H',
        '',
        'typedef enum {',
    ]
    for k in keys:
        lines.append(f'    {enum_name(k)},')
    lines.append('    HOP_STR_COUNT')
    lines.append('} hop_str_id;')
    lines.append('')
    lines.append('#ifdef HOP_I18N_DEFINE_TABLES')
    lines.append('static const char *const k_hop_i18n[2][HOP_STR_COUNT] = {')
    for code, label in LANGS:
        lines.append(f'    /* {code} ({label}) */')
        lines.append('    {')
        tbl = tables[code]
        for k in keys:
            lines.append(f'        {c_escape(tbl[k])}, /* {k} */')
        lines.append('    },')
    lines.append('};')
    lines.append('#endif /* HOP_I18N_DEFINE_TABLES */')
    lines.append('')
    lines.append('#endif /* HOP_I18N_TABLE_H */')
    lines.append('')
    return '\n'.join(lines)


def main() -> int:
    check_only = '--check' in sys.argv[1:]
    tables: dict[str, dict[str, str]] = {}
    for code, _ in LANGS:
        p = LOCALES / f'{code}.lang'
        if not p.is_file():
            raise SystemExit(f'Missing locale file: {p}')
        tables[code] = parse_lang(p)

    base_code = LANGS[0][0]
    base_keys = list(tables[base_code].keys())
    base_set = set(base_keys)
    for code, _ in LANGS[1:]:
        cur = tables[code]
        cur_set = set(cur.keys())
        missing = sorted(base_set - cur_set)
        extra = sorted(cur_set - base_set)
        if missing:
            raise SystemExit(f'Locale {code} missing keys: {", ".join(missing[:10])}')
        if extra:
            raise SystemExit(f'Locale {code} has unknown keys: {", ".join(extra[:10])}')
        for k in base_keys:
            s0 = fmt_signature(tables[base_code][k])
            s1 = fmt_signature(cur[k])
            if s0 != s1:
                raise SystemExit(f'Format specifier mismatch for "{k}": {base_code}={s0} vs {code}={s1}')

    generated = render_header(tables, base_keys)
    if check_only:
        if not OUT.is_file() or OUT.read_text(encoding='utf-8') != generated:
            raise SystemExit('src/core/i18n_table.h is out of date; run: python3 scripts/gen-i18n.py')
        print(f'PASS: i18n locale parity and generated table verified ({len(base_keys)} keys x {len(LANGS)} locales)')
        return 0

    OUT.write_text(generated, encoding='utf-8')
    print(f'Generated {OUT.relative_to(ROOT)} ({len(base_keys)} keys x {len(LANGS)} locales)')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
